#Playground {

// =====================================================================
// Lab1_2 — Завдання №2: Робота з типами
// =====================================================================

// 1. Ціле десяткове число 12 з мінімально необхідною розрядною сіткою.
//    12 вкладається в -128...127, тому мінімальний тип — Int8.
let num1: Int8 = 12
print("1. num1 =", num1, "| тип: Int8")

// 2. Ціле десяткове число -100 з мінімально необхідною розрядною сіткою.
//    -100 теж вкладається в Int8 (-128...127).
let num2: Int8 = -100
print("2. num2 =", num2, "| тип: Int8")

// 3. Ціле шістнадцяткове число, що рівне цілому десятковому числу 128.
//    128 НЕ вкладається в Int8 (макс. 127), але вкладається в UInt8 (0...255).
let num3: UInt8 = 0x80
print("3. num3 (0x80) =", num3, "| тип: UInt8")

// 4. Мінімальне десяткове значення числа у межах 16-розрядної сітки.
let num4: Int16 = Int16.min
print("4. Int16.min =", num4)

// 5. Максимальне десяткове значення числа у межах 64-розрядної сітки.
let num5: Int64 = Int64.max
print("5. Int64.max =", num5)

// 6. Число з плаваючою крапкою 10235.34 з мінімально необхідною
//    розрядною сіткою (7 значущих цифр — вкладається у Float).
let num6: Float = 10235.34
print("6. num6 =", num6, "| тип: Float")

// 7. Символ "а".
let ch: Character = "a"
print("7. ch =", ch)

// 8. Рядок "Hello World".
let str: String = "Hello World"
print("8. str =", str)

// 9. Істина.
let flag: Bool = true
print("9. flag =", flag)

// 10. Число 12 та його рядкове представлення "twelve" (Tuple).
let numberTuple: (Int, String) = (12, "twelve")
print("10. numberTuple =", numberTuple)

}
